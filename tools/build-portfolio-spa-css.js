'use strict';
// Keep standalone Portfolio CSS unchanged. Build a zero-specificity scope for
// its SPA mount, preventing body/.app-shell/button rules leaking to other pages.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const scope = ':where(#portofolioPartialMount)';
function selectors(value) {
  let depth = 0, quoted = '', start = 0; const out = [];
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (quoted) { if (c === '\\') i++; else if (c === quoted) quoted = ''; continue; }
    if (c === '"' || c === "'") { quoted = c; continue; }
    if (c === '(' || c === '[') depth++;
    if (c === ')' || c === ']') depth--;
    if (c === ',' && !depth) { out.push(value.slice(start, i)); start = i + 1; }
  }
  out.push(value.slice(start)); return out;
}
function namespace(selector) {
  const s = selector.trim();
  if (['html', 'body', '.app-shell', 'html.light body', 'html.light .app-shell', '[data-theme="light"] body', '[data-theme="light"] .app-shell'].includes(s)) return '';
  if (s === ':root') return scope;
  if (s === 'html.light') return 'html.light ' + scope;
  if (s === '[data-theme="light"]') return '[data-theme="light"] ' + scope;
  if (s.startsWith('html.light ')) return 'html.light ' + scope + ' ' + s.slice(11);
  if (s.startsWith('[data-theme="light"] ')) return '[data-theme="light"] ' + scope + ' ' + s.slice(21);
  if (s.startsWith('body ')) return scope + ' ' + s.slice(5);
  return scope + ' ' + s;
}
function compile(input) {
  const css = input.replace(/\/\*[\s\S]*?\*\//g, '');
  let out = '', pos = 0;
  while (pos < css.length) {
    const start = css.indexOf('{', pos);
    if (start < 0) { if (css.slice(pos).trim()) throw new Error('Unexpected trailing CSS'); break; }
    const head = css.slice(pos, start).trim();
    let depth = 1, quoted = '', end = start + 1;
    for (; end < css.length && depth; end++) {
      const c = css[end];
      if (quoted) { if (c === '\\') end++; else if (c === quoted) quoted = ''; continue; }
      if (c === '"' || c === "'") { quoted = c; continue; }
      if (c === '{') depth++; if (c === '}') depth--;
    }
    if (depth) throw new Error('Unbalanced CSS block: ' + head);
    const body = css.slice(start + 1, end - 1);
    if (/^@(media|supports|layer)\b/.test(head)) out += head + '{\n' + compile(body) + '}\n';
    else if (head.startsWith('@')) out += head + '{' + body + '}\n';
    else { const list = selectors(head).map(namespace).filter(Boolean); if (list.length) out += list.join(',\n') + '{' + body + '}\n'; }
    pos = end;
  }
  return out;
}
const sources = ['portfolio-command-center.css', 'portfolio-ai-workspace-v1.css'];
const output = '/* Generated by tools/build-portfolio-spa-css.js. Edit the original standalone styles, then regenerate. */\n' + sources.map(name => compile(fs.readFileSync(path.join(root,'public',name),'utf8'))).join('\n');
const target = path.join(root, 'public/portfolio-spa-scoped.css');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) throw new Error('Portfolio SPA CSS is out of date.');
} else fs.writeFileSync(target, output);
module.exports = { compile };
